CREATE TABLE master_transaction
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bidang              VARCHAR(255),
    anggaran            VARCHAR(255),
    kategory            VARCHAR(255),
    kode_program        VARCHAR(255),
    program_desc        VARCHAR(255),
    kode_kegiatan       VARCHAR(255),
    kegiatan_desc       VARCHAR(255),
    kode_sub_kegiatan   VARCHAR(255),
    sub_kegitan_desc    VARCHAR(255),
    kode_belanja        VARCHAR(255),
    belanja_desc        VARCHAR(255),
    pekerjaan           VARCHAR(255),
    pekerjaan_id        VARCHAR(255),
    no_dpa              VARCHAR(255),
    tgl_dpa             DATE,
    nilai_dpa           NUMERIC,
    tahun               INTEGER,
    no                  INTEGER,
    spk_no              VARCHAR(255),
    nilai_spk           NUMERIC,
    tgl_spk             DATE,
    tgl_spk_form        TIMESTAMP WITHOUT TIME ZONE,
    version             VARCHAR(255),
    tgl_start_pekerjaan DATE,
    tgl_end_pekerjaan   DATE,
    mitra_id            VARCHAR(255),
    mitra_name          VARCHAR(255),
    mitra_pimpinan      VARCHAR(255),
    mitra_no_rekening   VARCHAR(255),
    created_by          VARCHAR(255),
    created_date        VARCHAR(255),
    created_time        TIMESTAMP WITHOUT TIME ZONE,
    update_by           VARCHAR(255),
    last_update         VARCHAR(255),
    last_update_time    TIMESTAMP WITHOUT TIME ZONE,
    deleted_by          VARCHAR(255),
    is_deleted          BOOLEAN,
    deleted_date        VARCHAR(255),
    deleted_time        TIMESTAMP WITHOUT TIME ZONE
);

CREATE INDEX idx_master_transaction_spk_no ON master_transaction (spk_no);
CREATE INDEX idx_master_transaction_no ON master_transaction (no);
