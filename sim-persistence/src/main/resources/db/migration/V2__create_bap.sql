CREATE TABLE bap_transaction
(
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    master_transaction_id   BIGINT REFERENCES master_transaction (id),
    bap_no                  VARCHAR(255),
    bap_date                TIMESTAMP WITHOUT TIME ZONE,
    bap_date_text           DATE,
    bap_amount              NUMERIC,
    contrack_amount         NUMERIC,
    payment_method_id       VARCHAR(255),
    payment_method_desc     VARCHAR(255),
    hibah_no                VARCHAR(255),
    hibah_date              TIMESTAMP WITHOUT TIME ZONE,
    name_pengajuan          VARCHAR(255),
    phone_number_pengajuan  VARCHAR(255),
    pengajuan               JSONB,
    valid_itemanis          BOOLEAN,
    ringkasan_ref           JSONB,
    kwitansi_ref            JSONB,
    spp_ref                 JSONB,
    sp2d_ref                JSONB,
    spm_ref                 JSONB,
    validasi_ref            JSONB,
    rekom_ref               JSONB,
    created_by              VARCHAR(255),
    created_date            DATE,
    created_time            TIMESTAMP WITHOUT TIME ZONE,
    update_by               VARCHAR(255),
    last_update             DATE,
    last_update_time        TIMESTAMP WITHOUT TIME ZONE,
    deleted_by              VARCHAR(255),
    is_deleted              BOOLEAN,
    deleted_date            DATE,
    deleted_time            TIMESTAMP WITHOUT TIME ZONE,
    payment_no              VARCHAR(255)
);

CREATE INDEX idx_bap_transaction_bap_no ON bap_transaction (bap_no);
CREATE INDEX idx_bap_transaction_master_transaction_id ON bap_transaction (master_transaction_id);
CREATE INDEX idx_bap_transaction_created_date ON bap_transaction (created_date);
CREATE INDEX idx_bap_transaction_bap_date_text ON bap_transaction (bap_date_text);

CREATE TABLE bidang_tahun_active
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bidang_code   VARCHAR(255),
    bidang_desc   VARCHAR(255),
    tahun_active  VARCHAR(255)
);

CREATE INDEX idx_bidang_tahun_active_bidang_desc ON bidang_tahun_active (bidang_desc);

CREATE TABLE deleted_collection
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_trx            VARCHAR(255),
    no_trx            VARCHAR(255),
    type_trx          VARCHAR(255),
    value_trx         TEXT,
    created_by        VARCHAR(255),
    created_date      DATE,
    created_time      TIMESTAMP WITHOUT TIME ZONE,
    update_by         VARCHAR(255),
    last_update       DATE,
    last_update_time  TIMESTAMP WITHOUT TIME ZONE,
    deleted_by        VARCHAR(255),
    is_deleted        BOOLEAN,
    deleted_date      DATE,
    deleted_time      TIMESTAMP WITHOUT TIME ZONE
);
