CREATE TABLE kwitansi_transaction
(
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bap_id                  VARCHAR(255),
    master_transaction_id   BIGINT REFERENCES master_transaction (id),
    bap_no                  VARCHAR(255),
    description             TEXT,
    kepala_bidang_no        VARCHAR(255),
    kepala_bidang_name      VARCHAR(255),
    ppk_no                  VARCHAR(255),
    ppk_name                VARCHAR(255),
    pptk_no                 VARCHAR(255),
    pptk_name               VARCHAR(255),
    bpp_no                  VARCHAR(255),
    bpp_name                VARCHAR(255),
    direktur_no             VARCHAR(255),
    direktur_name           VARCHAR(255),
    kwitansi_date           TIMESTAMP WITHOUT TIME ZONE,
    created_by              VARCHAR(255),
    created_date            DATE,
    created_time            TIMESTAMP WITHOUT TIME ZONE,
    update_by               VARCHAR(255),
    last_update             DATE,
    last_update_time        TIMESTAMP WITHOUT TIME ZONE,
    deleted_by              VARCHAR(255),
    is_deleted              BOOLEAN,
    deleted_date            DATE,
    deleted_time            TIMESTAMP WITHOUT TIME ZONE
);

CREATE INDEX idx_kwitansi_transaction_bap_no ON kwitansi_transaction (bap_no);
CREATE INDEX idx_kwitansi_transaction_bap_id ON kwitansi_transaction (bap_id);
CREATE INDEX idx_kwitansi_transaction_master_transaction_id ON kwitansi_transaction (master_transaction_id);
CREATE INDEX idx_kwitansi_transaction_created_date ON kwitansi_transaction (created_date);
